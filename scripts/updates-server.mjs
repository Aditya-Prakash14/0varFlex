// scripts/updates-server.mjs — the "update server": a static file server over dist/, which is
// exactly what the generic provider is (the real VS Code serves latest-mac.yml + the zip from a
// CDN the same way). Run it, keep the app's configured feed pointed at http://localhost:8123,
// and the update loop works end to end.
//
//   node scripts/updates-server.mjs [port]

import { createServer } from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'dist');
const port = Number(process.argv[2] ?? 8123);

const CONTENT_TYPES = {
	'.yml': 'text/yaml; charset=utf-8',
	'.yaml': 'text/yaml; charset=utf-8',
	'.json': 'application/json; charset=utf-8',
	'.zip': 'application/zip',
	'.dmg': 'application/x-apple-diskimage',
	'.blockmap': 'application/octet-stream'
};

createServer(async (request, response) => {
	const requested = new URL(request.url ?? '/', `http://localhost:${port}`).pathname;
	const filePath = path.join(distDir, path.normalize(requested).replace(/^(\.\.[/\\])+/, ''));
	try {
		const info = await stat(filePath);
		if (!info.isFile()) {
			throw new Error('not a file');
		}
		const body = await readFile(filePath);
		response.writeHead(200, {
			'content-type': CONTENT_TYPES[path.extname(filePath)] ?? 'application/octet-stream',
			'content-length': String(body.length)
		});
		response.end(body);
		console.log(`${new Date().toISOString()}  200  ${requested} (${(info.size / 1024 / 1024).toFixed(2)} MB)`);
	} catch {
		response.writeHead(404, { 'content-type': 'text/plain' });
		response.end('not found');
		console.log(`${new Date().toISOString()}  404  ${requested}`);
	}
}).listen(port, () => {
	console.log(`update server: http://localhost:${port}  (serving ${path.relative(root, distDir)}/)`);
	console.log('the app reads Resources/app-update.yml (generated by electron-builder) for this URL');
});
